#!/usr/bin/env python3
"""catbench_vasp_stage.py — copy-only staging of a user's VASP tree for catbench.

Upstream `catbench.adsorption.vasp_preprocessing(dataset, coeff_setting)`
(catbench/adsorption/data/vasp.py:260) first runs
`cleanup_vasp_files(keep_files=["OSZICAR", "CONTCAR"])` on the tree it is
given — it DELETES every other file. So it must only ever see a copy, never
the originals and never a symlink tree into them. This script owns that
boundary and nothing else; the conversion itself stays upstream.

Ordered use (recipes/catbench.md §2 C):

  1. scan     — walk the originals WITHOUT following symlinks; list every
                CONTCAR+OSZICAR pair, every half-pair (missing DFT result,
                reported never invented), every symlink (refused), and write
                `mapping_proposal.json`. `slab`/`adslab` coefficients follow
                the upstream convention (adslab − slab − Σ gas); gas terms are
                listed as candidates that the USER confirms — never guessed.
                Its outputs are recorded in the owner marker (`--out` becomes an
                owned destination) and are kept, never rewritten, on a re-scan.
  2. stage    — with the confirmed coefficients (pass `--coeff` from OUTSIDE the
                destination: `<dest>/coeff_setting.json` is an output this script
                writes, so a file the user put there is refused, not overwritten):
                refuse symlinks
                anywhere under the source or under an existing staged copy,
                refuse a mountpoint at or under the selected source or
                destination root (an ordinary ancestor mount is normal and is
                not refused; unreadable mountinfo fails closed),
                refuse a destination inside/equal to the source or one this
                script did not create, refuse ANY content at a generated-output
                path unless the owner marker recorded this script writing that
                file for this source and it still hashes to the recorded value,
                create every output exclusively (O_EXCL|O_NOFOLLOW, no
                overwrite fallback) so an entry appearing between the check and
                the write fails instead of being written over,
                refuse to replace an existing staging
                that differs (a new owned --dest instead; this script never
                removes a staging or its outputs), hash the originals
                (`originals.sha256`, `sha256sum -c` compatible) plus a
                size/mtime inventory of EVERY original file, copy only the
                files upstream reads (CONTCAR, OSZICAR; `--all-files` for
                everything), re-hash the copy, and emit
                `stage_preprocess.py` + `run_stage.sh` (the rerunnable unit
                that calls upstream under a catbench-bearing interpreter).
                Nothing is executed here.
  3. verify   — re-hash the originals against `originals.sha256` and the
                inventory: unchanged originals are a verification item.

Usage:
  python3 scripts/catbench_vasp_stage.py scan   --source <originals> --out <stage>
  python3 scripts/catbench_vasp_stage.py stage  --source <originals> --dest <stage> \\
          --dataset-name my_dataset --coeff <stage>/coeff_setting.json --python <env>/bin/python
  python3 scripts/catbench_vasp_stage.py verify --source <originals> --dest <stage>
"""
