def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)
    s = sub.add_parser("scan"); s.add_argument("--source", required=True); s.add_argument("--out", required=True)
    t = sub.add_parser("stage")
    t.add_argument("--source", required=True); t.add_argument("--dest", required=True)
    t.add_argument("--dataset-name", required=True); t.add_argument("--coeff", required=True)
    t.add_argument("--python", required=True, help="catbench-bearing interpreter that will run run_stage.sh")
    t.add_argument("--all-files", action="store_true", help="copy every file, not just CONTCAR/OSZICAR")
    t.add_argument("--catbench-version", default=None, help="approved catbench version: stage_preprocess.py refuses any other")
    v = sub.add_parser("verify"); v.add_argument("--source", required=True); v.add_argument("--dest", required=True)
    args = ap.parse_args(argv)

    if args.cmd == "scan":
        derrs = _check_destination(Path(args.source), Path(args.out))   # --out obeys the same containment/ownership rules
        if derrs:
            print(json.dumps({"ok": False, "reason": "out_refused", "errors": derrs}, indent=2))
            return 3
        if (mr := _mount_refusals((("source", Path(args.source).resolve()), ("out", Path(args.out).resolve())))):
            print(json.dumps({"ok": False, **mr}, indent=2))
            return 3
        sc = scan(Path(args.source))
        proposal = propose_mapping(sc)
        out = Path(args.out)
        outputs = {"scan.json": json.dumps(sc, indent=2) + "\n",
                   "mapping_proposal.json": json.dumps(proposal, indent=2) + "\n"}
        owner = _owner_record(out)          # `stage` and `scan` share one record of what this script wrote
        unrelated = _unowned_outputs(out, owner, SCAN_OUTPUTS)
        if unrelated:
            print(json.dumps({"ok": False, "reason": "unrelated_destination_content",
                              "paths": [u["path"] for u in unrelated], "errors": [u["error"] for u in unrelated],
                              "detail": "something this scan would write already exists at that path and no owner record "
                                        "proves this script wrote it for this source; nothing was written. Give a new --out"},
                             indent=2))
            return 3
        # scan.json carries the scan's own timestamp, so an owned one is KEPT rather
        # than compared (it is never rewritten either); the proposal is deterministic
        # and a re-scan that would change it is refused.
        to_create, differs = _outputs_to_write(out, owner, {"mapping_proposal.json": outputs["mapping_proposal.json"]})
        if differs:
            print(json.dumps({"ok": False, "reason": "owned_outputs_differ", "paths": [d["path"] for d in differs],
                              "errors": [d["error"] for d in differs],
                              "detail": "this script wrote those files for this source but this scan would produce "
                                        "different content; nothing was written or removed. Give a new --out"}, indent=2))
            return 3
        if not (out / "scan.json").exists():
            to_create["scan.json"] = outputs["scan.json"]
        try:
            out.mkdir(parents=True, exist_ok=True)
            if owner is None:
                owner = _write_owner_marker(out, Path(args.source).resolve())   # so a later `stage --dest <out>` is accepted
            written = {name: write_exclusive(out / name, text) for name, text in to_create.items()}
            if written:
                _update_owner_marker(out, owner, written)
        except ExclusiveCreateFailed as exc:
            print(json.dumps({"ok": False, "reason": "exclusive_create_failed", "path": str(exc.path), "error": exc.error,
                              "detail": f"{exc.path} could not be created exclusively: something is already there that "
                                        "was not there when this scan checked. Nothing was written over or removed"}, indent=2))
            return 3
        print(json.dumps({"pairs": len(sc["pairs"]), "incomplete": len(sc["incomplete"]), "symlinks": sc["symlinks"],
                          "reactions": sorted(proposal["reactions"]), "gas_references": sorted(proposal["gas_references"]),
                          "problems": proposal["problems"], "ask": proposal["ask"],
                          "wrote": [str(out / "scan.json"), str(out / "mapping_proposal.json")]}, indent=2))
        return 3 if sc["symlinks"] else 0
    if args.cmd == "stage":
        coeff = json.loads(Path(args.coeff).read_text())
        rec = stage(Path(args.source), Path(args.dest), args.dataset_name, coeff, args.python,
                    all_files=args.all_files, catbench_version=args.catbench_version)
        print(json.dumps(rec, indent=2))
        return 0 if rec["ok"] else 3
    rec = verify(Path(args.source), Path(args.dest))
    print(json.dumps(rec, indent=2))
    return 0 if rec["ok"] else 3


if __name__ == "__main__":
    sys.exit(main())
