def _render_run_sh(dest: Path, python: str) -> str:
    return "\n".join(["#!/bin/sh", _GEN, "set -eu", f"cd {shlex.quote(str(dest))}",
                      f"exec {shlex.quote(str(python))} {shlex.quote(str(dest / 'stage_preprocess.py'))}"]) + "\n"


def _tree_hashes(root: Path) -> dict[str, str]:
    """`./<rel>` -> sha256 for EVERY regular file under root. Callers check
    `_tree_symlinks` first: a link here is refused, never silently skipped."""
    return {("./" + p.relative_to(root).as_posix()): sha256_file(p) for p in _iter_files(root, None)} if root.is_dir() else {}


def _tree_symlinks(root: Path) -> list[str]:
    """Every symlink anywhere under root, relative and sorted. A staged copy
    tree must hold none: upstream DELETES inside the tree it is given, so a link
    there would reach whatever it points at."""
    out = []
    if not root.is_dir() or root.is_symlink():
        return out
    for dirpath, dirnames, filenames in os.walk(root, followlinks=False):
        rel = os.path.relpath(dirpath, root)
        for name in list(dirnames) + filenames:
            if os.path.islink(os.path.join(dirpath, name)):
                out.append(os.path.normpath(os.path.join(rel, name)))
                if name in dirnames:
                    dirnames.remove(name)       # never descend through a link
    return sorted(out)


def copy_file(src: Path, dst: Path) -> None:
    """The single copy point (a real file copy, never a link), so a failing
    copy can be exercised without a failing filesystem. The destination is
    created exclusively: anything appearing under the temp tree since it was
    made fails the copy instead of being written through."""
    with os.fdopen(open_exclusive(dst), "wb") as out, src.open("rb") as fh:
        shutil.copyfileobj(fh, out)
    shutil.copystat(src, dst)


def _diff_trees(planned: dict[str, str], actual: dict[str, str]) -> dict:
    return {"extras": sorted(k for k in actual if k not in planned),
            "missing": sorted(k for k in planned if k not in actual),
            "changed": sorted(k for k in planned if k in actual and planned[k] != actual[k])}


def _inside_dest_not_link(path: Path, dest: Path, what: str) -> str | None:
    """Every path this script writes, renames or removes under dest must be a
    plain entry of the owned dest: not a symlink (or under one) and, once
    resolved, still inside dest. Nothing outside the owned tree is touched."""
    p = Path(path)
    for q in (p, *p.parents):
        if q == dest:
            break
        if q.is_symlink():
            return f"{what} {p} passes through a symlink at {q}; refusing (nothing under {dest} may point elsewhere)"
    if p.exists():
        r = p.resolve()
        if dest not in r.parents:
            return f"{what} {p} resolves to {r}, outside the owned destination {dest}; refusing"
    return None


def _unowned_outputs(dest: Path, record: dict | None, names: tuple[str, ...]) -> list[dict]:
    """Ownership is a RECORD, not a shape. A file already sitting where this call
    writes is accepted only when the owner marker records this script writing that
    name for this source AND the file still hashes to the recorded value. Valid
    JSON, a well-formed manifest or a generated-by marker prove nothing about who
    wrote a file, so no content is inspected here — no record, a missing entry, a
    drifted hash, a symlink or a non-regular entry all refuse."""
    recorded = (record or {}).get("outputs") or {}
    out = []
    for name in names:
        p = dest / name
        try:
            st_mode = os.lstat(p).st_mode
        except OSError:
            continue                        # nothing there: it will be created exclusively
        if stat.S_ISLNK(st_mode):
            out.append({"path": str(p), "error": f"{p} exists and is a symlink; refusing to write over it"})
        elif not stat.S_ISREG(st_mode):
            out.append({"path": str(p), "error": f"{p} exists and is not a regular file; refusing to write over it"})
        elif name not in recorded:
            out.append({"path": str(p), "error": f"{p} exists and no {OWNER_MARKER} record says this script wrote it; "
                                                 "refusing to write over content it does not own"})
        else:
            try:
                digest = sha256_file(p)
            except OSError as exc:
                out.append({"path": str(p), "error": f"{p} exists and cannot be read ({exc}); refusing to write over it"})
                continue
            if digest != recorded[name]:
                out.append({"path": str(p), "error": f"{p} exists but hashes to {digest}, not the {recorded[name]} this "
                                                     "script recorded writing; refusing to write over content that changed since"})
    return out


def _outputs_to_write(dest: Path, record: dict | None, planned: dict[str, str]) -> tuple[dict[str, str], list[dict]]:
    """Split the planned outputs into the ones to create and the owned ones this
    call would change. An owned output whose bytes this call reproduces exactly is
    KEPT, never rewritten; one that would change is refused, because this script
    overwrites nothing — a new owned --dest is the remedy."""
    recorded = (record or {}).get("outputs") or {}
    to_create, differs = {}, []
    for name, text in planned.items():
        p = dest / name
        if not p.exists():
            to_create[name] = text
        elif sha256_text(text) != recorded.get(name):
            differs.append({"path": str(p), "error": f"{p} holds this script's earlier output and this call would write "
                                                     "different content there; refusing to overwrite it"})
    return to_create, differs


def stage(source: Path, dest: Path, dataset_name: str, coeff_setting: dict, python: str,
          *, all_files: bool = False, catbench_version: str | None = None) -> dict:
    """Copy the needed originals into an owned destination and write the
    rerunnable conversion unit. The staged copy tree `<dest>/<dataset_name>`
    must equal the planned file set EXACTLY (no extras, nothing missing,
    same hashes): a fresh staging is copied into a temp dir inside dest,
    validated, then renamed into place; an existing identical copy tree is
    kept as is; an existing copy tree that differs from the plan (files
    removed from the source since, edits, strays), a symlink anywhere under
    it, a leftover temp dir, or previous outputs without their copy tree are
    REFUSED — nothing is removed or replaced by this script; the user gives a
    new owned --dest. A copy that fails part way RETAINS its temp tree and
    names it. Originals are never written.

    Generated outputs are owned by RECORD: the owner marker holds the sha256 of
    every file this script wrote for this source, and a file already at one of
    those paths is only accepted when the record names it and it still hashes to
    the recorded value. An owned output whose bytes this call would reproduce is
    kept untouched; one that would change is refused (`owned_outputs_differ`)
    rather than overwritten, so `stage_record.json` on a reused staging stays the
    one the first run wrote — the fresh record is returned and printed only.
    Everything is created with O_EXCL|O_NOFOLLOW, so an entry planted between the
    check and the write fails the create (`exclusive_create_failed`) instead of
    being written over."""
    if not _DATASET_NAME_RE.match(dataset_name or ""):
        return {"ok": False, "reason": "dataset_name_invalid",
                "detail": f"{dataset_name!r} must match {_DATASET_NAME_RE.pattern} (it names a directory and the raw_data JSON)"}
    derrs = _check_destination(Path(source), Path(dest))     # root symlinks checked before resolve()
    if derrs:
        return {"ok": False, "reason": "destination_refused", "errors": derrs}
    source, dest = Path(source).resolve(), Path(dest).resolve()
    if (mr := _mount_refusals((("source", source), ("destination", dest)))):
        return {"ok": False, **mr}               # refused before the tree is walked, let alone written
    sc = scan(source)
    if sc["symlinks"]:
        return {"ok": False, "reason": "symlinks_in_source", "symlinks": sc["symlinks"],
                "detail": "staging refuses to traverse symlinks (a link tree into the originals would be cleaned in place); "
                          "resolve or exclude them explicitly and rerun"}
    proposal = propose_mapping(sc)
    errs = validate_coeff(coeff_setting, proposal)
    if errs:
        return {"ok": False, "reason": "coeff_setting_invalid", "errors": errs}
    blocking = blocking_problems(proposal, coeff_setting)
    if blocking:
        return {"ok": False, "reason": "missing_dft_results", "problems": blocking,
                "detail": "a DFT result upstream needs is missing or unparseable; it is reported, never computed or invented"}

    only = None if all_files else NEEDED_FILES
    planned = {("./" + p.relative_to(source).as_posix()): sha256_file(p) for p in _iter_files(source, only)}
    copy_root = dest / dataset_name
    tmp_root = dest / f".{dataset_name}.staging.tmp"
    previous_outputs = [p for p in (dest / "raw_data", dest / "stage_result.json") if p.exists() or p.is_symlink()]
    # every entry under dest that this call would read/rename/create/write is checked for a symlink escape first
    watched = [("copy tree", copy_root), ("temp dir", tmp_root), ("raw_data", dest / "raw_data"),
               ("stage_result.json", dest / "stage_result.json")] + [(n, dest / n) for n in GENERATED_OUTPUTS]
    escapes = [m for what, p in watched if dest.exists() and (m := _inside_dest_not_link(p, dest, what))]
    if escapes:
        return {"ok": False, "reason": "destination_refused", "errors": escapes}
    owner = _owner_record(dest)                 # the sole ownership evidence: what this script recorded writing
    unrelated = _unowned_outputs(dest, owner, RECORDED_OUTPUTS)
    if copy_root.exists() and not copy_root.is_dir():
        unrelated.append({"path": str(copy_root), "error": f"{copy_root} exists and is not a directory; refusing to write over it"})
    if unrelated:
        return {"ok": False, "reason": "unrelated_destination_content", "paths": [u["path"] for u in unrelated],
                "errors": [u["error"] for u in unrelated],
                "detail": "something this call would write already exists at that path and no owner record proves this "
                          "script wrote it for this source; nothing was written or removed. Give a new owned --dest"}
    if tmp_root.exists():                       # leftover of an aborted attempt, or something else with that name: not ours to remove
        return {"ok": False, "reason": "staging_tmp_exists",
                "detail": f"{tmp_root} already exists; nothing was written. Inspect and remove it yourself, or give a new owned --dest"}
    reused = False
    if copy_root.exists():                      # re-stage into an owned destination
        if (links := _tree_symlinks(copy_root)):
            return {"ok": False, "reason": "symlinks_in_staged_tree", "symlinks": [str(copy_root / ln) for ln in links],
                    "detail": f"{copy_root} holds symlinks; a staged tree must be real files only (upstream deletes "
                              "inside the tree it is given, so a link would reach outside it). Nothing was written "
                              "or removed; give a new owned --dest"}
        diff = _diff_trees(planned, _tree_hashes(copy_root))
        if any(diff.values()):
            return {"ok": False, "reason": "staged_tree_differs", "staged_diff": diff,
                    "previous_outputs": [str(p) for p in previous_outputs],
                    "detail": f"{copy_root} already holds a staging that is not what the source would produce now; "
                              "nothing was written or removed. Give a new owned --dest (this script never replaces a staging)"}
        reused = True                           # identical copy tree already in place: keep it, copy nothing
    elif previous_outputs:
        return {"ok": False, "reason": "stale_outputs_without_copy_tree",
                "previous_outputs": [str(p) for p in previous_outputs],
                "detail": f"{dest} holds outputs of an earlier run but no {copy_root}; nothing was written or removed. "
                          "Give a new owned --dest"}

    run_sh = dest / "run_stage.sh"
    # every output's bytes are known before anything is written: an owned one this
    # call would reproduce exactly is kept, one it would change is refused here
    outputs = {"coeff_setting.json": json.dumps(coeff_setting, indent=2, sort_keys=True) + "\n",
               "mapping_proposal.json": json.dumps(proposal, indent=2) + "\n",
               "originals.sha256": manifest_text(planned),
               "originals.inventory.json": json.dumps(inventory(source), indent=2, sort_keys=True) + "\n",
               "stage_preprocess.py": _render_preprocess_py(dataset_name, catbench_version),
               "run_stage.sh": _render_run_sh(dest, python)}
    to_create, differs = _outputs_to_write(dest, owner, outputs)
    if differs:
        return {"ok": False, "reason": "owned_outputs_differ", "paths": [d["path"] for d in differs],
                "errors": [d["error"] for d in differs],
                "detail": "this script wrote those files for this source but this call would produce different content; "
                          "nothing was written or removed (it never overwrites its own outputs either). Give a new owned --dest"}
    try:
        dest.mkdir(parents=True, exist_ok=True)
        if owner is None:
            owner = _write_owner_marker(dest, source)   # first use: created exclusively
        copied, written = 0, {}
        if not reused:
            # From here a write has begun. Anything that goes wrong RETAINS the temp
            # tree (never deleted here) and names it, so the user can inspect it; the
            # originals were only ever read, and a rerun refuses the leftover.
            mkdir_exclusive(tmp_root)
            made = {tmp_root}
            try:
                for rel in planned:
                    target = tmp_root / rel[2:]
                    _mkdir_chain(tmp_root, target.parent, made)
                    copy_file(source / rel[2:], target)  # a real file copy; never a link
                    copied += 1
                staged_hashes = _tree_hashes(tmp_root)
            except OSError as exc:
                return {"ok": False, "reason": "copy_failed", "retained_tmp": str(tmp_root), "copied_files": copied,
                        "error": f"{type(exc).__name__}: {exc}",
                        "detail": f"the copy into {tmp_root} failed part way; the partial copy is RETAINED for inspection "
                                  "and is never removed by this script (a rerun refuses it as staging_tmp_exists). "
                                  "The originals were only read, never written"}
            if (links := _tree_symlinks(tmp_root)):
                return {"ok": False, "reason": "symlinks_in_staged_tree", "retained_tmp": str(tmp_root),
                        "symlinks": [str(tmp_root / ln) for ln in links],
                        "detail": f"{tmp_root} holds symlinks; a staged tree must be real files only. It is RETAINED for "
                                  "inspection, nothing was renamed and nothing was removed"}
            staged_check = _diff_trees(planned, staged_hashes)
            if any(staged_check.values()):      # exact path set, extras included
                return {"ok": False, "reason": "staged_tree_mismatch", "staged_check": staged_check,
                        "retained_tmp": str(tmp_root),
                        "detail": f"the copy under {tmp_root} is not exactly the planned file set; it is RETAINED for "
                                  "inspection, nothing was renamed and nothing was removed"}
            if copy_root.exists() or copy_root.is_symlink():   # appeared since the check: the rename must not replace it
                raise ExclusiveCreateFailed(copy_root, FileExistsError(17, "File exists"))
            try:
                tmp_root.rename(copy_root)      # copy_root did not exist (checked above): a plain rename, nothing replaced
            except OSError as exc:
                return {"ok": False, "reason": "copy_failed", "retained_tmp": str(tmp_root), "copied_files": copied,
                        "error": f"{type(exc).__name__}: {exc}",
                        "detail": f"the validated copy could not be renamed to {copy_root}; it is RETAINED under "
                                  f"{tmp_root} and is never removed by this script. The originals were only read"}
        final_check = _diff_trees(planned, _tree_hashes(copy_root))
        if any(final_check.values()):
            return {"ok": False, "reason": "staged_tree_mismatch", "staged_check": final_check,
                    "detail": f"{copy_root} does not hold exactly the planned file set"}
        copy_check = check_manifest(copy_root, planned)
        if not copy_check["unchanged"]:
            return {"ok": False, "reason": "copy_hash_mismatch", "copy_check": copy_check}

        for name, text in outputs.items():      # owned-and-identical ones are not in to_create: they are kept as they are
            if name in to_create:
                written[name] = write_exclusive(dest / name, text, 0o755 if name == "run_stage.sh" else 0o644)
        record = {"ok": True, "source": str(source), "dest": str(dest), "dataset_name": dataset_name,
                  "copied_files": copied, "hashed_files": len(planned), "copied_subset": list(only) if only else "ALL",
                  "python": python, "catbench_version": catbench_version, "run": str(run_sh),
                  "expected_output": str(dest / "raw_data" / f"{dataset_name}_adsorption.json"),
                  "staged_tree_exact": True, "reused_identical_staging": reused,
                  "previous_outputs_kept": [str(p) for p in previous_outputs],
                  "problems": proposal["problems"], "warnings": coeff_warnings(coeff_setting),
                  "staged_utc": utc_now()}
        if not (dest / "stage_record.json").exists():   # an owned one is kept: it is never rewritten (see the docstring)
            written["stage_record.json"] = write_exclusive(dest / "stage_record.json", json.dumps(record, indent=2) + "\n")
        if written:
            _update_owner_marker(dest, owner, written)  # the record names the bytes that actually landed
        return record
    except ExclusiveCreateFailed as exc:
        return {"ok": False, "reason": "exclusive_create_failed", "path": str(exc.path), "error": exc.error,
                **({"retained_tmp": str(tmp_root)} if tmp_root.exists() else {}),
                "detail": f"{exc.path} could not be created exclusively: something is already there that was not there "
                          "when this call checked. Nothing was written over, nothing was renamed and nothing was "
                          "removed; inspect that path, then give a new owned --dest"}


def verify(source: Path, dest: Path) -> dict:
    source, dest = Path(source).resolve(), Path(dest).resolve()
    manifest = dest / "originals.sha256"
    inv_path = dest / "originals.inventory.json"
    if not manifest.is_file():
        return {"ok": False, "reason": f"no {manifest}"}
    hashes = check_manifest(source, read_manifest(manifest))
    inv_now = inventory(source)
    inv_then = json.loads(inv_path.read_text()) if inv_path.is_file() else {}
    inv_diff = {"missing": sorted(k for k in inv_then if k not in inv_now),
                "added": sorted(k for k in inv_now if k not in inv_then),
                "changed": sorted(k for k in inv_then if k in inv_now and inv_then[k] != inv_now[k])}
    symlinks = scan(source)["symlinks"]      # a link that appeared since staging is a change too
    ok = hashes["unchanged"] and not any(inv_diff.values()) and not symlinks
    return {"ok": ok, "hashes": hashes, "inventory_diff": inv_diff, "symlinks_now": symlinks, "verified_utc": utc_now()}


