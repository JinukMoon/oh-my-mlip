# ── Thread caps for in-env prep steps (thread-limited-host safety) ──
# On hosts with task limits (e.g. HPC login nodes with cgroup pids.max constraints),
# unbounded thread pools from torch/TF/JAX can overrun the per-user task limit during
# weight preparation and D3 compilation, leaving weights unmaterialized. Cap them
# uniformly: 4 BLAS/OMP threads + 1 inductor compile worker is plenty for a one-shot
# prep step and harmless on unconstrained hosts.
# ── Low-parallel mode under a per-user task limit (HPC login nodes) ──
# A login node can cap tasks (processes + threads) per user with the cgroup pids
# controller (pids.max = 150 on a EuroHPC login node) while `ulimit -u` looks huge.
# mamba's .pyc compile pool (os.cpu_count() workers), OpenBLAS threads and
# ninja/pip build jobs then hit the cap: the pool deadlocks, and the user's
# shell, agent and new logins can no longer fork. scripts/task_limit.py reads
# the limit and, below 4096 tasks or when OMM_MAX_PARALLEL is set, exports caps
# for every pool the install starts (a value already set wins).
if command -v python3 >/dev/null 2>&1; then
  eval "$(python3 "$OH_MY_MLIP_HOME/scripts/task_limit.py" --exports 2>/dev/null || true)"
fi
if [ -n "${OMM_LOW_PARALLEL:-}" ]; then
  echo "install.sh: this host limits tasks per user (${OMM_TASK_LIMIT:-unknown}); building with at most"
  echo "  ${OMM_LOW_PARALLEL} parallel jobs/threads (no .pyc precompile; Python writes it on first import)."
  echo "  Keep other heavy work off this login node until the install ends; set OMM_MAX_PARALLEL to change it."
fi

THREAD_CAPS=(env OMP_NUM_THREADS="${OMM_LOW_PARALLEL:-4}" MKL_NUM_THREADS="${OMM_LOW_PARALLEL:-4}"
  OPENBLAS_NUM_THREADS="${OMM_LOW_PARALLEL:-4}" NUMEXPR_NUM_THREADS="${OMM_LOW_PARALLEL:-4}"
  TORCHINDUCTOR_COMPILE_THREADS=1)

# D3 kernel prebuild for one env (scripts/build_d3.py): a no-op when
# pair_d3.so exists or the env has no torch/catbench (GRACE). Mode "error" (a
# fresh install): a failed build fails the env (return 1, no sentinel). Mode
# "warn" (an env that was already installed): a failed build prints a WARNING
# with the log and the rerun command, leaves the failed marker <prefix>/.omm_d3
# (setup_verify and --status report it) and is listed again at the end of the
# run; the env stays ready.
OMM_D3_WARNINGS=()
OMM_PREFETCH_WARNINGS=()

# Download every weight of an env's variants, so the env runs on a node without
# internet (HPC compute nodes): explicit weight paths through oh_my_mlip.fetch,
# by-name weights (mace_mp('medium-mpa-0'), SevenNet, ORB, ...) by building each
# calculator once on the CPU (no calculation). Gated variants without a Hugging
# Face token are skipped and listed. A variant that cannot be prefetched is a
# warning, not a failed env: the framework still downloads it on first use
# where there is internet. OMM_PREFETCH=0 skips this step.
prefetch_weights() {
  local env_name="$1" prefix="$2"
  [ "${OMM_PREFETCH:-1}" != "0" ] || return 0
  echo "  downloading the weights of '$env_name' for offline use (scripts/prefetch_weights.py) ..."
  "${THREAD_CAPS[@]}" CUDA_VISIBLE_DEVICES="" "$prefix/bin/python" "$OH_MY_MLIP_HOME/scripts/prefetch_weights.py" "$env_name" \
    || OMM_PREFETCH_WARNINGS+=("$env_name (see $prefix/.omm_prefetch.json)")
}

build_d3_kernel() {
  local env_name="$1" prefix="$2" mode="${3:-error}" rc=0
  local log="$prefix/.omm_d3_build.log"
  echo "  D3 kernel (pair_d3.so) for '$env_name' ..."
  # torch's cpp_extension needs ninja. The sm120 siblings ship it; the base
  # recipes do not, and a host without a system ninja (Rocky 8 on an HPC
  # login node) then fails with "Ninja is required". Add the same pinned wheel
  # the sevennet/nequip recipes use, only to an env that has nvcc and no ninja.
  if [ -x "$prefix/bin/nvcc" ] && [ ! -x "$prefix/bin/ninja" ] && [ -x "$prefix/bin/pip" ]; then
    echo "  adding ninja==1.13.0 to '$env_name' (needed to build the D3 kernel) ..."
    "${THREAD_CAPS[@]}" "$prefix/bin/pip" install --quiet "ninja==1.13.0" \
      || echo "  could not install ninja into '$env_name'; the D3 build below will say why it fails." >&2
  fi
  "${THREAD_CAPS[@]}" python3 "$OH_MY_MLIP_HOME/scripts/build_d3.py" "$prefix" --log "$log" --on-fail "$mode" || rc=$?
  if [ "$rc" -eq 0 ]; then
    return 0
  fi
  if [ "$mode" = "warn" ] && [ "$rc" -eq 3 ]; then
    OMM_D3_WARNINGS+=("$env_name (log: $log)")
    return 0
  fi
  echo "  D3 kernel build FAILED for '$env_name' — no sentinel written. Build log: $log" >&2
  echo "  Retry after fixing it: python3 $OH_MY_MLIP_HOME/scripts/build_d3.py $prefix" >&2
  return 1
}

install_one() {
  local env_name="$1"
  local prefix="$ENVS_DIR/$env_name"
  local sentinel="$prefix/.omm_ready"
  local weights_prepared=1

  # Stop before any download when no recipe is known to work on this GPU: a
  # base-recipe wheel without kernels for it would build, then fail with "no
  # kernel image is available" at the first calculation.
  if ! pick_recipe "$env_name"; then
    echo "install.sh: STOP '$env_name' (GPU ${HOST_ARCH:-unknown}): $RECIPE_REASON." >&2
    echo "  Nothing was downloaded or installed. See envs/_arch_recipes.json and docs/host_requirements.md." >&2
    return 1
  fi
  local stem="$RECIPE_STEM"
  local recipe="$ENVS_DIR/$stem.yml"
  if [ "$stem" != "$env_name" ]; then
    echo "  '$env_name' on $HOST_ARCH: building from the sibling recipe envs/$stem.yml ($RECIPE_REASON)"
  fi

  if [ ! -e "$recipe" ]; then
    echo "install.sh: SKIP '$env_name' (no recipe at $recipe)" >&2
    return 1
  fi

  # One build per env at a time: a second install.sh (an agent re-running the
  # command while the first still builds in the background) would otherwise
  # judge the half-built env and act on it.
  # mkdir is atomic: exactly one process creates the lock directory. A lock
  # left by a dead holder is removed once and taken again; any other failure
  # stops this env (fail closed) instead of building without the lock.
  local lock="$ENVS_DIR/.$env_name.install.lock" holder
  if ! mkdir "$lock" 2>/dev/null; then
    holder="$(cat "$lock/pid" 2>/dev/null || true)"
    if [ -n "$holder" ] && kill -0 "$holder" 2>/dev/null; then
      echo "install.sh: '$env_name' is already being built by install.sh (pid $holder). Wait for it:" >&2
      echo "  it is done when $prefix/.omm_ready exists or that pid has exited." >&2
      return 3
    fi
    rm -rf "$lock"
    if ! mkdir "$lock" 2>/dev/null; then
      echo "install.sh: could not take the build lock $lock for '$env_name'; not building it." >&2
      return 3
    fi
  fi
  if ! echo "$$" > "$lock/pid"; then
    rm -rf "$lock"
    echo "install.sh: could not write $lock/pid; not building '$env_name'." >&2
    return 3
  fi
  OMM_LOCKS+=("$lock")

  if [ -e "$sentinel" ]; then
    # Trust but verify: a sentinel can LIE — observed on this host when an old
    # install.sh (pre fail-safe guards) wrote it after a killed build (the env
    # had no torch/fairchem yet was marked ready). Re-verify the registered
    # imports; a stale sentinel is removed and the env falls through to
    # adopt-or-heal below instead of being trusted blindly.
    local vrc=0
    verify_env_imports "$env_name" "$prefix" || vrc=$?
    if [ "$vrc" -eq 0 ] && [ "$(built_recipe "$prefix" "$env_name")" != "$stem" ]; then
      # Built from another arch's recipe (a base env on an sm120 host): its
      # imports pass, but its wheels carry no kernels for this GPU.
      echo "  '$env_name' is installed from envs/$(built_recipe "$prefix" "$env_name").yml, but this GPU ($HOST_ARCH) needs" >&2
      echo "  envs/$stem.yml (the installed wheels carry no kernels for it)." >&2
      if [ "$REBUILD" -eq 1 ] && [ ! -L "$prefix" ]; then
        echo "  --rebuild given: deleting $prefix and building it from envs/$stem.yml." >&2
        "$CONDA_BIN" env remove -p "$prefix" -y >/dev/null 2>&1 || true
        rm -rf "$prefix"
        vrc=99
      else
        echo "  Nothing was changed. Rebuild it with: ./install.sh --rebuild $env_name" >&2
        return 1
      fi
    fi
    if [ "$vrc" -eq 0 ]; then
      echo "  '$env_name' already installed (sentinel present + imports verified) — skipping."
      # an env installed before the D3 prebuild existed gets its kernel now
      # (a no-op when pair_d3.so is already there); the env is in use, so a
      # failed build warns and leaves a marker instead of failing it
      build_d3_kernel "$env_name" "$prefix" warn || return 1
      # an env installed before weights were downloaded at install time
      [ -e "$prefix/.omm_prefetch.json" ] || prefetch_weights "$env_name" "$prefix"
      return 0
    fi
    if [ "$vrc" -eq 99 ]; then
      :  # removed above for a rebuild from the right recipe
    elif [ "$vrc" -eq 124 ] || [ "$vrc" -eq 10 ]; then
      echo "  '$env_name' is marked ready but $(import_check_reason "$vrc"). Nothing was changed;" >&2
      echo "  run install.sh again, or pass --rebuild to delete $prefix and build it from the recipe." >&2
      return 1
    else
      echo "  '$env_name' sentinel present but imports FAIL — stale sentinel; removing it and re-entering adopt-or-heal." >&2
      rm -f "$sentinel"
    fi
  fi

  # Disk preflight before the solve: a build needs DISK_FLOOR_GB free
  # (oh_my_mlip/hub.py, the value the survey, sweep and guardrail use); a
  # full disk otherwise fails 20 minutes in with "No space left on device".
  if [ ! -x "$prefix/bin/python" ]; then
    local floor free_gb
    floor="${OMM_DISK_FLOOR_GB:-$(grep -oE '^DISK_FLOOR_GB = [0-9.]+' "$OH_MY_MLIP_HOME/oh_my_mlip/hub.py" 2>/dev/null | grep -oE '[0-9.]+$' || echo 30)}"
    free_gb="$(df -Pk "$ENVS_DIR" 2>/dev/null | awk 'NR==2 {printf "%d", $4/1048576}')"
    if [ -n "$free_gb" ] && [ "$free_gb" -lt "${floor%.*}" ]; then
      echo "install.sh: only $free_gb GB free under $ENVS_DIR; building '$env_name' needs at least ${floor%.*} GB" >&2
      echo "  (an env is 5-15 GB plus download caches). Free space and re-run; nothing was built." >&2
      return 1
    fi
  fi

  # Preflight: warn now (before the long build) if this recipe's CUDA runtime is
  # newer than the host driver can expose — the env will run CPU-only here.
  warn_driver_skew "$env_name" "$recipe"

  # Adopt-or-heal: a prefix WITHOUT the sentinel is an interrupted install
  # (built but post-steps unfinished) or a broken build. Never duplicate-build
  # over it and never crash into conda's "prefix already exists" — verify the
  # framework imports inside the EXISTING interpreter: on success ADOPT the env
  # (skip the build, resume the post-install steps below); on failure remove it
  # and rebuild from the recipe.
  local skip_build=0
  if [ -L "$prefix" ]; then
    # A symlink points at an env this script did not build; it is never removed.
    echo "  '$env_name': $prefix is a symlink to $(readlink "$prefix"); install.sh never modifies or" >&2
    echo "  removes a linked env. Remove the link yourself to build here, or use adopt_env.py." >&2
    return 1
  fi
  if [ -x "$prefix/bin/python" ]; then
    echo "  '$env_name' env exists without sentinel — verifying imports (adopt-or-heal) ..."
    local vrc=0
    verify_env_imports "$env_name" "$prefix" || vrc=$?
    if [ "$vrc" -eq 0 ] && [ "$(built_recipe "$prefix" "$env_name")" != "$stem" ]; then
      vrc=98   # built from another arch's recipe: never adopt it as this GPU's env
    fi
    if [ "$vrc" -eq 0 ]; then
      echo "  imports OK — adopting the existing env; resuming post-install steps (no rebuild)."
      skip_build=1
    elif [ "$REBUILD" -eq 1 ] && [ "$vrc" -ne 124 ] && [ "$vrc" -ne 10 ]; then
      echo "  $(import_check_reason "$vrc"); --rebuild given: deleting $prefix and rebuilding from the recipe."
      "$CONDA_BIN" env remove -p "$prefix" -y >/dev/null 2>&1 || true
      rm -rf "$prefix"
    elif [ "$vrc" -eq 98 ]; then
      echo "  '$env_name': $prefix was built from envs/$(built_recipe "$prefix" "$env_name").yml; this GPU needs envs/$stem.yml." >&2
      echo "  Nothing was deleted. Rebuild it with: ./install.sh --rebuild $env_name" >&2
      return 1
    else
      echo "  '$env_name': $prefix has an interpreter but $(import_check_reason "$vrc")." >&2
      echo "  Nothing was deleted. An interrupted build usually looks like this. To delete this env and" >&2
      echo "  build it again from the recipe, re-run with --rebuild:  ./install.sh --rebuild $env_name" >&2
      return 1
    fi
  elif [ -e "$prefix" ]; then
    echo "  '$env_name' prefix exists but has no interpreter (partial build) — removing $prefix and rebuilding."
    rm -rf "$prefix"
  fi

  # Multi-pass build sidecar: a few envs cannot be built by a single
  # `conda env create` (e.g. equflash — fairchem-core 1.10 vs torch 2.9.1 is a
  # pip ResolutionImpossible that only a documented multi-pass pip resolves). If
  # `envs/<env>.build.sh` exists it OWNS env creation + all pip passes (invoked
  # with PREFIX as $1); otherwise the single-pass recipe path is used. Either way
  # install.sh still owns the catbench + D3 kernel build + sentinel steps below.
  local build_sidecar="$ENVS_DIR/$stem.build.sh"
  if [ "$skip_build" -eq 0 ]; then
    # Explicit failure checks: install_one is invoked as `install_one || rc=1`,
    # and bash SUPPRESSES `set -e` inside a function called in such a context —
    # without these guards a failed build would fall through the post-steps and
    # could even write the ready sentinel (observed in a fixture simulation).
    if [ "${OMM_USE_LOCK:-0}" = "1" ]; then
      # Exact replay: the conda @EXPLICIT package list, then the pip set with
      # --no-deps (no resolution), both generated by scripts/gen_env_lock.py
      # from a passing build run. A missing lock is a hard failure —
      # never a silent fall back to the (resolving) recipe.
      local lock_conda="$ENVS_DIR/locks/$stem.conda.txt"
      local lock_pip="$ENVS_DIR/locks/$stem.pip.txt"
      if [ ! -e "$lock_conda" ] || [ ! -e "$lock_pip" ]; then
        echo "  OMM_USE_LOCK=1 but no lock for '$env_name' recipe '$stem' ($lock_conda, $lock_pip) — no sentinel written." >&2
        return 1
      fi
      echo "  creating env '$env_name' from lock $lock_conda + $lock_pip ..."
      if grep -q "repo.anaconda.com" "$lock_conda"; then
        echo "  note: this lock fetches $(grep -c "repo.anaconda.com" "$lock_conda") package(s) from Anaconda's defaults channel" >&2
        echo "        (repo.anaconda.com), whose terms of service apply; the recipe build does not use it." >&2
      fi
      # same Terms-of-Service guard as the recipe build below
      CONDA_DEFAULT_CHANNELS="${CONDA_DEFAULT_CHANNELS:-https://conda.anaconda.org/conda-forge}" \
      "$CONDA_BIN" create --yes --prefix "$prefix" --file "$lock_conda" || {
        echo "  conda create from lock FAILED for '$env_name' — no sentinel written." >&2
        return 1
      }
      "$prefix/bin/pip" install --no-deps -r "$lock_pip" || {
        echo "  pip install from lock FAILED for '$env_name' — no sentinel written." >&2
        return 1
      }
    elif [ -e "$build_sidecar" ]; then
      echo "  building env '$env_name' via multi-pass sidecar $build_sidecar ..."
      bash "$build_sidecar" "$prefix" || {
        echo "  build sidecar FAILED for '$env_name' — no sentinel written." >&2
        return 1
      }
    else
      echo "  creating env '$env_name' from $recipe ..."
      # Every recipe lists `nodefaults`, yet conda >= 25 still checks the Terms of
      # Service of its implicit default channels (repo.anaconda.com) and a fresh
      # Miniconda stops with CondaToSNonInteractiveError before solving (seen on
      # a new Ubuntu 26.04 host, conda 26.9). Pointing default_channels at
      # conda-forge for this one command avoids that without accepting anything
      # on the user's behalf; a value the user set wins. Sidecars already pass
      # --override-channels.
      CONDA_DEFAULT_CHANNELS="${CONDA_DEFAULT_CHANNELS:-https://conda.anaconda.org/conda-forge}" \
      "$CONDA_BIN" env create --prefix "$prefix" --file "$recipe" || {
        echo "  conda env create FAILED for '$env_name' — no sentinel written." >&2
        return 1
      }
    fi
    # which recipe this env came from: install.sh compares it on every run, and
    # setup_verify records it with the arch it was verified on.
    printf '%s %s%s\n' "$stem" "${HOST_ARCH:-none}" "$([ "${OMM_USE_LOCK:-0}" = "1" ] && echo " lock")" > "$prefix/.omm_recipe"
  fi

  # Install catbench as a post-create step (WITH its deps). catbench is
  # deliberately NOT in the recipe pip block: a bare '--no-deps' line inside a
  # conda pip block is an invalid requirement and breaks 'conda env create'.
  # Installing it here (after torch is already pinned by the recipe) is safe: a
  # real-build test confirmed catbench 1.1.2 does NOT downgrade the pinned
  # torch+cuXXX wheel, while '--no-deps' would drop catbench's real runtime deps
  # (requests, xlsxwriter, ...) and break 'from catbench.adsorption import ...'.
  echo "  installing catbench (==${CATBENCH_PIN}) into '$env_name' ..."
  "$prefix/bin/pip" install "catbench==${CATBENCH_PIN}" || {
    echo "  catbench install FAILED for '$env_name' — no sentinel written." >&2
    return 1
  }

  # Pre-stage upstream weights whose in-package downloader can 202-block on some
  # networks. A few frameworks (eqnorm, matris) fetch their checkpoint from a
  # plain figshare.com URL *inside their own package* into ~/.cache/<pkg>/ and
  # then skip re-download if the file "exists" (even a 0-byte one). If a
  # scripts/prestage_<env>_weights.py helper exists, run it now (pure stdlib,
  # env-independent) to stage the file via the working ndownloader subdomain
  # before the user ever builds a calculator. Non-fatal: on failure the
  # framework still falls back to its own download on first use.
  prestage="$OH_MY_MLIP_HOME/scripts/prestage_${env_name}_weights.py"
  if [ -e "$prestage" ]; then
    echo "  pre-staging weights for '$env_name' via $(basename "$prestage") ..."
    python3 "$prestage" || echo "  (weight pre-stage skipped/failed; framework will retry its own download on first use)"
  fi

  # Prepare weights that require the ENV's own tooling (not pure stdlib): some
  # frameworks ship a TRAINING checkpoint that must be transformed by an in-env
  # CLI before inference — DeePMD `dp --pt freeze` (single-head frozen .pth), PET
  # `mtt export` (exported metatomic .pt), GRACE `grace_models download` + flatten.
  # These CANNOT run under the system python (they need `dp`/`mtt`/`grace_models`
  # from the env), so run them with the ENV interpreter AFTER the build, passing
  # --target-root models/<env> uniformly. Without this a fresh build leaves the
  # weight unprepared and inference fails with "... does not exist".
  prepare="$OH_MY_MLIP_HOME/scripts/prepare_${env_name}_weights.py"
  if [ -e "$prepare" ]; then
    echo "  preparing weights for '$env_name' via $(basename "$prepare") (env interpreter) ..."
    local prc=0
    "${THREAD_CAPS[@]}" "$prefix/bin/python" "$prepare" --target-root "$OH_MY_MLIP_HOME/models/$env_name" || prc=$?
    if [ "$prc" -eq 4 ]; then
      # NequIP / Allegro on a host without a GPU (an HPC login node): the model
      # package is downloaded, the per-GPU compile has to run on a GPU node.
      echo "  '$env_name': model package downloaded; the GPU compile runs later on a GPU node (see above)."
    elif [ "$prc" -ne 0 ]; then
      echo "  weight prepare FAILED for '$env_name' ($(basename "$prepare")); inference cannot work until it succeeds." >&2
      weights_prepared=0
    fi
  fi

  prefetch_weights "$env_name" "$prefix"

  # Build the D3 kernel now (scripts/build_d3.py), with this env's own ninja,
  # nvcc and conda compiler, so the first D3 call through the bare interpreter
  # (resolve()["python"], no env bin on PATH) never has to compile. A failed
  # build fails this env: no sentinel, so a re-run retries it.
  build_d3_kernel "$env_name" "$prefix" || return 1

  if [ "${weights_prepared:-1}" -eq 0 ]; then
    # The sentinel means "ready to use". Writing it after a failed weight
    # preparation made a re-run skip the env (docs/help.md promises a re-run
    # repairs it), leaving inference failing on a missing checkpoint forever.
    echo "  '$env_name' built but its weights are not prepared — no sentinel written, so a re-run retries." >&2
    return 1
  fi
  : > "$sentinel"
  echo "  '$env_name' ready -> $prefix/bin/python"

  if [ "$WITH_ACCEL" -eq 1 ]; then
    echo "  [--with-accel] curated GPU compile/accel for '$env_name' (printed only;"
    echo "    upstream-doc, GPU-unverified — run on your GPU host; see docs/compile.md):"
    print_accel_for_env "$env_name"
  fi
}

rc=0
for env_name in "${TARGETS[@]}"; do
  install_one "$env_name" || rc=1
done

echo
if [ "${#OMM_D3_WARNINGS[@]}" -gt 0 ]; then
  echo "install.sh: WARNING: the D3 kernel could not be built for these already-installed envs" >&2
  echo "  (they stay usable without D3; each has a 'state=failed' marker in <prefix>/.omm_d3):" >&2
  for w in "${OMM_D3_WARNINGS[@]}"; do echo "    $w" >&2; done
fi
if [ "${#OMM_PREFETCH_WARNINGS[@]}" -gt 0 ]; then
  echo "install.sh: WARNING: some weights could not be downloaded ahead of use. These envs work where there" >&2
  echo "  is internet, but a node without internet (an HPC compute node) cannot load those variants:" >&2
  for w in "${OMM_PREFETCH_WARNINGS[@]}"; do echo "    $w" >&2; done
fi
if [ "$rc" -eq 0 ]; then
