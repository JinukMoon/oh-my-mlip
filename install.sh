#!/usr/bin/env bash
# install.sh — oh-my-mlip build-from-recipe orchestrator (PRIMARY install path).
#
# Build-from-recipe is the ONLY install path: this script builds a model's env
# from envs/<env>.yml (conda + PyPI) on the current host (host-correct by
# construction), installs catbench, and builds the D3 kernel (pair_d3.so).
# No prebuilt environment is distributed. It writes the on-disk layout:
#   $OH_MY_MLIP_HOME/envs/<env>/bin/python   (+ a .omm_ready sentinel)
#
# Usage:
#   ./install.sh [--dry-run] [--all] [TARGET ...]
#     TARGET     one or more env names (mace, sevennet, ...) OR registered model
#                names (MACE, SevenNet, ...), case-insensitive. Model names are
#                resolved to their env via models.json, so 'install.sh MACE',
#                'install.sh mace', and 'install.sh SevenNet' all work.
#                With no TARGET, install.sh refuses: pass --all to build every
#                recipe (that is every framework, hundreds of GB and hours).
#     --dry-run  print the plan and exit WITHOUT downloading/installing anything
#     --all      build every recipe (required when no TARGET is named)
#                (the no-network / contributor inspection path).
#     --status   inspect the install state of each target env and exit (ready /
#                partial / broken / not installed); changes nothing. An env
#                without the .omm_ready sentinel is NEVER duplicate-built: the
#                real install verifies its imports and adopts it (resuming the
#                post-install steps); if they fail it stops and deletes nothing.
#     --rebuild  allow deleting an env whose imports fail (an interrupted build)
#                and building it again from the recipe. Never applies to a
#                symlinked env, or when the import check timed out.
#     --with-accel  opt-in (default OFF): also PRINT the curated GPU compile/accel
#                commands (NequIP/Allegro/SevenNet) for each targeted env, as in
#                docs/compile.md; this flag only prints them (the NequIP/Allegro
#                compile itself runs during install via scripts/prepare_*_weights.py).
#                '--with-accel --dry-run' prints the install plan AND the accel
#                commands, installing nothing.
#
#   Recipe per GPU architecture: on a GPU listed in envs/_arch_recipes.json
#                (sm120) an env may be built from a SIBLING recipe such as
#                envs/mace.cu128.yml instead of envs/mace.yml (whose CUDA wheels
#                carry no kernels for that GPU); older GPUs keep the base recipe.
#                When no recipe is known to work on this GPU, install.sh stops
#                before downloading anything and says why. The recipe used is
#                written to envs/<env>/.omm_recipe. OMM_INSTALL_ARCH=sm120 plans
#                for another GPU (with --dry-run). scripts/select_recipe.py decides.
#
#   OMM_USE_LOCK=1 ./install.sh <env>
#                exact replay instead of the recipe: conda create from
#                envs/locks/<recipe>.conda.txt (@EXPLICIT) then
#                pip install --no-deps -r envs/locks/<recipe>.pip.txt
#                (<recipe> = the env, or its sibling, e.g. mace.cu128). Locks are
#                generated by scripts/gen_env_lock.py from a successful build.
#                A missing lock fails the env.
#
# Requires conda (or mamba) on PATH. The D3 kernel is built at the end of each
# env's install by scripts/build_d3.py with the env's own nvcc; a failed build
# fails the env. An env without any nvcc keeps D3 off (the MLIP still runs).

set -euo pipefail

# ── Resolve clone root and shared env ──
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]:-$0}")" && pwd)"
export OH_MY_MLIP_HOME="${OH_MY_MLIP_HOME:-$SCRIPT_DIR}"
# Same order as oh_my_mlip/hub.py. A copy inside an agent's plugin cache is
# replaced on every plugin update, so envs are never built there.
# the real path, as oh_my_mlip/hub.py resolves it: a symlink into the cache is refused too
OMM_REAL_HOME="$(cd "$OH_MY_MLIP_HOME" 2>/dev/null && pwd -P || echo "$OH_MY_MLIP_HOME")"
case "$OMM_REAL_HOME/" in
  */.claude/plugins/*|*/.codex/plugins/*)
    echo "[stop] $OH_MY_MLIP_HOME is the copy of oh-my-mlip inside the agent's plugin cache, not a hub:" >&2
    echo "       it is replaced on every plugin update, and envs built there are lost." >&2
    echo "       Use your own clone: export OH_MY_MLIP_HOME=<clone> (default ~/.oh-my-mlip; clone" >&2
    echo "       https://github.com/JinukMoon/oh-my-mlip.git there if it does not exist). AGENTS.md §9.0." >&2
    exit 2 ;;
esac
ENVS_DIR="$OH_MY_MLIP_HOME/envs"

# pip gives up on a wheel after 5 resumes of a dropped download; a CUDA wheel
# is several hundred MB, and on a flaky link that failed a first SevenNet
# build after an hour. Every pip pass (conda env create and the sidecars)
# inherits these; a value the user already set wins.
export PIP_RESUME_RETRIES="${PIP_RESUME_RETRIES:-50}"
export PIP_RETRIES="${PIP_RETRIES:-10}"
export PIP_DEFAULT_TIMEOUT="${PIP_DEFAULT_TIMEOUT:-60}"

OMM_LOCKS=()
# only the locks this process took (each holds our pid) are removed on exit
trap 'rm -rf ${OMM_LOCKS[@]+"${OMM_LOCKS[@]}"} 2>/dev/null' EXIT
DRY_RUN=0
STATUS=0
WITH_ACCEL=0
REBUILD=0
REQUESTED=()

# catbench ships in EVERY env (D3 dispersion + adsorption benchmarking are
# pre-wired). PINNED, not floating: a new catbench release could pull deps that
# shift the validated torch stack. Bump deliberately (single knob here) and
# re-verify; override for testing a release candidate without editing:
#   OMM_CATBENCH_VERSION=1.2.0 ./install.sh <env>
CATBENCH_PIN="${OMM_CATBENCH_VERSION:-1.1.4}"

for arg in "$@"; do
  case "$arg" in
    --dry-run) DRY_RUN=1 ;;
    --all) BUILD_ALL=1 ;;
    --status) STATUS=1 ;;
    --with-accel) WITH_ACCEL=1 ;;
    --rebuild) REBUILD=1 ;;
    -h|--help)
      sed -n '2,33p' "${BASH_SOURCE[0]:-$0}"
      exit 0
      ;;
    -*)
      echo "install.sh: unknown option '$arg'" >&2
      exit 2
      ;;
    *) REQUESTED+=("$arg") ;;
  esac
done

# ── Discover available recipes ──
available_envs() {
  local f name
  for f in "$ENVS_DIR"/*.yml; do
    [ -e "$f" ] || continue
    name="$(basename "$f" .yml)"
    # _expected.json-style files and sibling recipes (<env>.<tag>.yml, e.g.
    # mace.cu128) are not envs of their own; select_recipe picks a sibling.
    case "$name" in _*|*.*) continue ;; esac
    printf '%s\n' "$name"
  done
}

mapfile -t ALL_ENVS < <(available_envs)
if [ "${#ALL_ENVS[@]}" -eq 0 ]; then
  echo "install.sh: no env recipes found in $ENVS_DIR/*.yml" >&2
  exit 1
fi

# ── Resolve an argument to an env name ──
# Accepts EITHER an env name (e.g. 'mace') OR a registered MODEL name
# (e.g. 'MACE', 'SevenNet'), case-insensitively. A model name is mapped to its
# env via the 'env' field in models.json. Prints the resolved env on stdout, or
# echoes the original argument unchanged if nothing matches (the caller then
# SKIPs it with a clear message). This is why 'install.sh MACE' and
# 'install.sh mace' and 'install.sh SevenNet' all work.
MODELS_JSON="$OH_MY_MLIP_HOME/models.json"

resolve_to_env() {
  local arg="$1" lower env_match
  # 1) Direct (case-insensitive) match against an env recipe name.
  lower="$(printf '%s' "$arg" | tr '[:upper:]' '[:lower:]')"
  for env_match in "${ALL_ENVS[@]}"; do
    if [ "$lower" = "$(printf '%s' "$env_match" | tr '[:upper:]' '[:lower:]')" ]; then
      printf '%s\n' "$env_match"
      return 0
    fi
  done
  # 2) Treat the arg as a registered MODEL name; map model -> env via models.json
  #    (case-insensitive on the model key). Python is used only to read JSON; if
  #    it (or the file) is unavailable we fall through to returning the arg as-is.
  #    Prefer python3, but fall back to python so a host that only ships `python`
  #    still resolves a registered model instead of silently skipping it.
  local py_bin
  py_bin="$(command -v python3 || command -v python || true)"
  if [ -e "$MODELS_JSON" ] && [ -n "$py_bin" ]; then
    env_match="$(MODELS_JSON="$MODELS_JSON" ARG="$arg" "$py_bin" - <<'PYEOF' 2>/dev/null || true
import json
import os

try:
    with open(os.environ["MODELS_JSON"], "r", encoding="utf-8") as fh:
        data = json.load(fh)
except Exception:
    raise SystemExit(0)

want = os.environ["ARG"].lower()
for name, info in data.items():
    if name.startswith("_") or not isinstance(info, dict):
        continue
    env = info.get("env")
    if not isinstance(env, str):
        continue
    # family name (MACE) OR any of its version keys (MACE-MPA-0): the hub's own
    # "not installed" message and README/docs/start.md tell users the version
    # form, so accepting only the family silently SKIPped a correct command.
    versions = info.get("versions")
    if name.lower() == want or (
        isinstance(versions, dict) and any(v.lower() == want for v in versions)
    ):
        print(env)
        break
PYEOF
)"
    if [ -n "$env_match" ]; then
      printf '%s\n' "$env_match"
      return 0
    fi
  fi
  # 3) No match -> echo the arg unchanged; the caller SKIPs it loudly.
  printf '%s\n' "$arg"
}

# ── Opt-in accel surfacing (--with-accel) ──
# PRINTS the curated GPU compile/accel command(s) for an env, when the registry
# records an accel block for that framework. Upstream-doc, GPU-UNVERIFIED: this
# only surfaces the command (never runs a GPU compile). See docs/compile.md.
print_accel_for_env() {
  local env_name="$1" py_bin
  py_bin="$(command -v python3 || command -v python || true)"
  [ -e "$MODELS_JSON" ] && [ -n "$py_bin" ] || return 0
  MODELS_JSON="$MODELS_JSON" ENV="$env_name" "$py_bin" - <<'PYEOF' 2>/dev/null || true
import json
import os

try:
    with open(os.environ["MODELS_JSON"], "r", encoding="utf-8") as fh:
        data = json.load(fh)
except Exception:
    raise SystemExit(0)

env = os.environ["ENV"]
for name, info in data.items():
    if name.startswith("_") or not isinstance(info, dict):
        continue
    if info.get("env") != env:
        continue
    blocks = []
    for key in ("accel", "accel_lammps"):
        blk = info.get(key)
        if isinstance(blk, dict):
            blocks.append((key, blk))
    for version, vinfo in info.get("versions", {}).items():
        blk = vinfo.get("accel") if isinstance(vinfo, dict) else None
        if isinstance(blk, dict):
            blocks.append((f"{version}.accel", blk))
    if not blocks:
        print(f"    (no accel block recorded for env '{env}')")
        continue
    for label, blk in blocks:
        print(f"    [{name}.{label}] tool={blk.get('tool')}  (upstream-doc, GPU-unverified)")
        print(f"      install: {blk.get('install')}")
        if blk.get("compile_cmd"):
            print(f"      compile: {blk.get('compile_cmd')}")
        print(f"      load:    {blk.get('load_note')}")
        if blk.get("verify"):
            print(f"      verify:  {blk.get('verify')}")
PYEOF
}

# ── Driver <-> CUDA-runtime preflight ──
# A recipe pins torch==X.Y.Z+cuNNN; that cuNNN (e.g. cu130 = CUDA 13.0) is the CUDA
# RUNTIME the wheel needs, which in turn needs a host NVIDIA driver new enough to
# expose that CUDA version. If the host driver is too old (e.g. host CUDA 12.9 vs a
# +cu130 build) the MLIP still BUILDS and runs on CPU, but torch.cuda is unavailable
# so GPU inference fails at load with a cryptic "driver too old". Warn up front and
# inform the user about driver compatibility. Non-fatal (CPU still works).
# cuNNN encodes major*10+minor, so int("130")=130 and a host "12.9" -> 12*10+9 = 129
# compare directly.
warn_driver_skew() {
  local env_name="$1" recipe="$2"
  local cu env_cu host_mm host_cu env_major env_minor
  cu="$(grep -oE 'torch==[0-9.]+\+cu[0-9]+' "$recipe" 2>/dev/null | grep -oE 'cu[0-9]+' | head -1 || true)"
  [ -n "$cu" ] || return 0                       # CPU-only recipe / no pinned torch wheel
  env_cu="${cu#cu}"
  local smi
  smi="$(command -v nvidia-smi || { [ -x /usr/lib/wsl/lib/nvidia-smi ] && echo /usr/lib/wsl/lib/nvidia-smi; } || true)"
  [ -n "$smi" ] || return 0
  host_mm="$("$smi" 2>/dev/null | grep -oE 'CUDA Version: [0-9]+\.[0-9]+' | grep -oE '[0-9]+\.[0-9]+' | head -1 || true)"
  [ -n "$host_mm" ] || return 0
  host_cu="$(( ${host_mm%.*} * 10 + ${host_mm#*.} ))"
  if [ "$env_cu" -gt "$host_cu" ]; then
    env_major="$(( env_cu / 10 ))"
    env_minor="$(( env_cu % 10 ))"
    echo "  WARNING driver skew for '$env_name': recipe torch is +$cu (needs CUDA ${env_major}.${env_minor} runtime),"
    echo "    but the host NVIDIA driver exposes only CUDA ${host_mm} -> torch.cuda will be UNAVAILABLE."
    echo "    The MLIP will build and run on CPU. GPU inference requires a newer"
    echo "    NVIDIA driver with CUDA ${env_major}.x support. See AGENTS.md, ground rule 6."
  fi
}

# ── Existing-env import verification (adopt-or-heal support) ──
# Runs the framework's registered `import` lines (models.json) inside an
# EXISTING env interpreter. Used when a prefix exists without the .omm_ready
# sentinel (interrupted install): a passing import means the env is real and
# must be ADOPTED, not duplicate-built; a failure means broken -> rebuild.
verify_env_imports() {
  # 0 = imports OK; 124 = timed out; 10 = the check itself could not run
  # (no interpreter / unreadable models.json); anything else = an import failed.
  # The env's own interpreter reads models.json, so no host python3 is needed.
  local env_name="$1" prefix="$2" imports tmpf rc
  [ -x "$prefix/bin/python" ] || return 10
  imports="$("$prefix/bin/python" - "$env_name" "$OH_MY_MLIP_HOME/models.json" <<'PY'
import json
import sys

env, path = sys.argv[1], sys.argv[2]
with open(path, encoding="utf-8") as fh:
    data = json.load(fh)
for info in data.values():
    if isinstance(info, dict) and info.get("env") == env:
        print("\n".join(info.get("import", [])))
        break
PY
)" || return 10
  [ -n "$imports" ] || return 0   # no registered imports -> interpreter presence is enough
  tmpf="$(mktemp)"
  printf '%s\n' "$imports" > "$tmpf"
  rc=0
  timeout "${OMM_IMPORT_CHECK_TIMEOUT:-600}" "$prefix/bin/python" "$tmpf" >/dev/null 2>&1 || rc=$?
  rm -f "$tmpf"
  return "$rc"
}

# Why an import check did not pass, for the halt messages below.
import_check_reason() {
  case "$1" in
    124) echo "the import check timed out after ${OMM_IMPORT_CHECK_TIMEOUT:-600} s (a slow disk or a cold network home can do this)" ;;
    10)  echo "the import check could not run (no interpreter in the env, or models.json unreadable)" ;;
    *)   echo "a registered import failed (exit $1)" ;;
  esac
}

# ── Recipe per GPU architecture ──
# Sets RECIPE_STEM (envs/<stem>.yml, sidecar envs/<stem>.build.sh, locks
# envs/locks/<stem>.*.txt) and RECIPE_REASON for an env. Returns 3 when this GPU
# has no recipe known to work, and also when the choice cannot be made (no host
# python, or scripts/select_recipe.py failed): the caller stops before
# installing anything. Falling back to the base recipe there would install, on
# a newer GPU, wheels with no kernels for it -- the failure this table exists
# to prevent. scripts/select_recipe.py holds the rule (envs/_arch_recipes.json).
HOST_ARCH=""
pick_recipe() {
  local env_name="$1" py_bin out err rc=0
  RECIPE_STEM=""; RECIPE_REASON=""
  py_bin="$(command -v python3 || command -v python || true)"
  if [ -z "$py_bin" ]; then
    RECIPE_REASON="cannot choose a recipe: no python3 (or python) on PATH to run scripts/select_recipe.py, which reads envs/_arch_recipes.json and the GPU arch. Put a python 3 on PATH (any version; it uses the standard library only) and re-run"
    return 3
  fi
  err="$(mktemp)"
  out="$("$py_bin" "$OH_MY_MLIP_HOME/scripts/select_recipe.py" "$env_name" --json 2>"$err")" || rc=$?
  if [ -z "$out" ] || ! printf '%s' "$out" | "$py_bin" -c 'import json,sys; json.load(sys.stdin)' >/dev/null 2>&1; then
    RECIPE_REASON="cannot choose a recipe: scripts/select_recipe.py failed (exit $rc with $py_bin): $(tail -n 3 "$err" | tr '\n' ' ')"
    rm -f "$err"
    return 3
  fi
  rm -f "$err"
  RECIPE_STEM="$(printf '%s' "$out" | "$py_bin" -c 'import json,sys; print(json.load(sys.stdin)["recipe"] or "")')"
  RECIPE_REASON="$(printf '%s' "$out" | "$py_bin" -c 'import json,sys; print(json.load(sys.stdin)["reason"])')"
  HOST_ARCH="$(printf '%s' "$out" | "$py_bin" -c 'import json,sys; print(json.load(sys.stdin)["arch"] or "none")')"
  [ "$rc" -eq 0 ] && [ -n "$RECIPE_STEM" ] && return 0
  return 3
}

# The recipe an existing env was built from (the base recipe when unrecorded:
# every env built before envs/<env>/.omm_recipe existed used the base recipe).
built_recipe() {
  local prefix="$1" env_name="$2" r=""
  [ -r "$prefix/.omm_recipe" ] && r="$(head -1 "$prefix/.omm_recipe" | awk '{print $1}')"
  printf '%s\n' "${r:-$env_name}"
}

# No env names: building all 20 frameworks is hundreds of GB and hours of work,
# so it has to be asked for. A bare `./install.sh` used to start exactly that.
if [ "${#REQUESTED[@]}" -eq 0 ] && [ "${BUILD_ALL:-0}" -eq 0 ]; then
  echo "install.sh: name at least one target, or pass --all." >&2
  echo "  ./install.sh MACE            # one model (or its env name: mace)" >&2
  echo "  ./install.sh MACE SevenNet   # several" >&2
  echo "  ./install.sh --all           # every recipe: ${#ALL_ENVS[@]} envs, hundreds of GB" >&2
  echo "  ./install.sh --dry-run --all # see that plan without installing" >&2
  exit 2
fi
if [ "${#REQUESTED[@]}" -eq 0 ]; then
  TARGETS=("${ALL_ENVS[@]}")
else
  TARGETS=()
  for arg in "${REQUESTED[@]}"; do
    TARGETS+=("$(resolve_to_env "$arg")")
  done
fi

# A name that is neither an env nor a registered family or variant stops here,
# before --status or any build, with the valid names (as registry.py lists them).
UNKNOWN=()
for t in "${TARGETS[@]}"; do
  case "$t" in
    *.*) if [ -e "$ENVS_DIR/$t.yml" ]; then
           echo "install.sh: '$t' is a sibling recipe of env '${t%%.*}', not an env: install '${t%%.*}'," >&2
           echo "  and install.sh builds it from envs/$t.yml on the GPU that recipe is for (envs/_arch_recipes.json)." >&2
         fi
         UNKNOWN+=("$t") ;;
    *) [ -e "$ENVS_DIR/$t.yml" ] || UNKNOWN+=("$t") ;;
  esac
done
if [ "${#UNKNOWN[@]}" -gt 0 ]; then
  families=""
  py_bin="$(command -v python3 || command -v python || true)"
  if [ -n "$py_bin" ] && [ -e "$MODELS_JSON" ]; then
    families="$("$py_bin" -c 'import json,sys; print(", ".join(k for k in json.load(open(sys.argv[1])) if not k.startswith("_")))' "$MODELS_JSON" 2>/dev/null || true)"
  fi
  echo "install.sh: not an env, model family or variant: ${UNKNOWN[*]}" >&2
  echo "  envs: ${ALL_ENVS[*]}" >&2
  [ -n "$families" ] && echo "  families: $families (any of their variant names works too)" >&2
  exit 2
fi

# ── Detect conda / mamba (skipped under --dry-run and --status, which change nothing) ──
# An agent's non-interactive shell usually lacks the PATH lines `conda init`
# writes into ~/.bashrc, so an installed conda is looked for in the usual
# places before it is declared missing; when found, its bin/ goes first on PATH
# so the sidecar builds and conda's own pip see it too.
find_conda_off_path() {
  local cand
  for cand in "${MAMBA_EXE:-}" "${CONDA_EXE:-}" \
              "$HOME"/miniforge3/bin/mamba "$HOME"/mambaforge/bin/mamba \
              "$HOME"/miniforge3/bin/conda "$HOME"/mambaforge/bin/conda \
              "$HOME"/miniconda3/bin/conda "$HOME"/anaconda3/bin/conda \
              /opt/conda/bin/conda /opt/miniconda3/bin/conda /opt/miniforge3/bin/conda; do
    [ -n "$cand" ] && [ -x "$cand" ] && { echo "$cand"; return 0; }
  done
  return 1
}
CONDA_BIN=""
if [ "$DRY_RUN" -eq 0 ] && [ "$STATUS" -eq 0 ]; then
  if command -v mamba >/dev/null 2>&1; then
    CONDA_BIN="mamba"
  elif command -v conda >/dev/null 2>&1; then
    CONDA_BIN="conda"
  elif found="$(find_conda_off_path)"; then
    echo "install.sh: conda is installed at $found but is not on PATH in this shell; using it." >&2
    echo "  To make it permanent for non-interactive shells: export PATH=\"$(dirname "$found"):\$PATH\"" >&2
    conda_dir="$(dirname "$found")"
    export PATH="$conda_dir:$PATH"
    CONDA_BIN="$found"
  else
    echo "install.sh: no conda or mamba found (not on PATH, not in \$CONDA_EXE, not under ~/miniforge3," >&2
    echo "  ~/mambaforge, ~/miniconda3, ~/anaconda3 or /opt). If you have one elsewhere, put its bin/ on" >&2
    echo "  PATH and re-run; otherwise install Miniforge or Miniconda first." >&2
    exit 1
  fi
fi

echo "oh-my-mlip install (build from recipe)"
echo "  OH_MY_MLIP_HOME = $OH_MY_MLIP_HOME"
echo "  recipes dir     = $ENVS_DIR"
echo "  targets         = ${TARGETS[*]}"
if [ "$WITH_ACCEL" -eq 1 ]; then
  echo "  accel           = ON (--with-accel): curated GPU compile/accel commands"
  echo "                    will be PRINTED per env (upstream-doc, GPU-unverified;"
  echo "                    nothing GPU-compiled). See docs/compile.md."
else
  echo "  accel           = OFF (default). Pass --with-accel to print the curated"
  echo "                    GPU compile/accel commands (NequIP/Allegro/SevenNet)."
fi
# The D3 kernel (pair_d3.so) is built per env by scripts/build_d3.py with the
# env's OWN cuda-nvcc (every recipe ships one), ninja and conda compiler; a
# system toolkit is only the fallback for an env without nvcc.
echo "  D3 kernel       = built per env with its own nvcc (scripts/build_d3.py);"
echo "                    system nvcc: $(command -v nvcc || echo 'none on PATH (not needed)')"

if [ "$DRY_RUN" -eq 1 ]; then
  echo
  echo "[--dry-run] Plan only; nothing downloaded or installed."
  for env_name in "${TARGETS[@]}"; do
    if ! pick_recipe "$env_name"; then
      echo "  STOP '$env_name' on ${HOST_ARCH:-this GPU}: $RECIPE_REASON"
      continue
    fi
    recipe="$ENVS_DIR/$RECIPE_STEM.yml"
    build_sidecar="$ENVS_DIR/$RECIPE_STEM.build.sh"
    echo "  recipe for '$env_name' (GPU ${HOST_ARCH:-none}): envs/$RECIPE_STEM.yml ($RECIPE_REASON)"
    if [ -e "$recipe" ]; then
      if [ -e "$build_sidecar" ]; then
        echo "  would build env '$env_name' via multi-pass sidecar $build_sidecar -> $ENVS_DIR/$env_name"
        echo "    (sidecar owns env creation + all pip passes; a single 'conda env create' cannot resolve this env)"
      else
        echo "  would create env '$env_name' from $recipe -> $ENVS_DIR/$env_name"
      fi
      echo "    then: $ENVS_DIR/$env_name/bin/pip install catbench==${CATBENCH_PIN}"
      prestage="$OH_MY_MLIP_HOME/scripts/prestage_${env_name}_weights.py"
      if [ -e "$prestage" ]; then
        echo "    then: python3 $prestage  (pre-stage upstream weights before first use)"
      fi
      prepare="$OH_MY_MLIP_HOME/scripts/prepare_${env_name}_weights.py"
      if [ -e "$prepare" ]; then
        echo "    then: $ENVS_DIR/$env_name/bin/python $prepare --target-root $OH_MY_MLIP_HOME/models/$env_name  (prepare weights with the env interpreter)"
      fi
      echo "    then: python3 $OH_MY_MLIP_HOME/scripts/build_d3.py $ENVS_DIR/$env_name  (D3 kernel, pair_d3.so)"
      warn_driver_skew "$env_name" "$recipe"
    else
      echo "  SKIP '$env_name': no recipe at $recipe"
    fi
    if [ "$WITH_ACCEL" -eq 1 ]; then
      echo "  [--with-accel] curated GPU compile/accel for '$env_name' (printed only):"
      print_accel_for_env "$env_name"
    fi
  done
  echo "  would: source $OH_MY_MLIP_HOME/env.sh"
  echo "  would: build the D3 kernel per env with its own nvcc/ninja/compiler (scripts/build_d3.py)"
  exit 0
fi

if [ "$STATUS" -eq 1 ]; then
  echo
  echo "[--status] Installed-env inspection (nothing is changed)."
  for env_name in "${TARGETS[@]}"; do
    prefix="$ENVS_DIR/$env_name"
    if [ -e "$prefix/.omm_ready" ]; then
      state="ready       (built + post-steps done; install.sh will skip)"
    elif [ -x "$prefix/bin/python" ]; then
      state="partial     (env exists, no sentinel; install.sh will verify imports and ADOPT it, or stop and ask for --rebuild)"
    elif [ -e "$prefix" ]; then
      state="broken      (prefix without interpreter; install.sh will remove + rebuild)"
    else
      state="not installed (install.sh will build from the recipe)"
    fi
    printf '  %-14s %s\n' "$env_name" "$state"
    if grep -qx 'state=failed' "$prefix/.omm_d3" 2>/dev/null; then
      printf '  %-14s D3 kernel build FAILED earlier: %s\n' "" "$(grep -m1 '^log=' "$prefix/.omm_d3" | cut -d= -f2-)"
    fi
    if pick_recipe "$env_name"; then
      if [ -x "$prefix/bin/python" ] && [ "$(built_recipe "$prefix" "$env_name")" != "$RECIPE_STEM" ]; then
        printf '  %-14s built from envs/%s.yml, but this GPU (%s) needs envs/%s.yml: rebuild with --rebuild\n' \
          "" "$(built_recipe "$prefix" "$env_name")" "$HOST_ARCH" "$RECIPE_STEM"
      else
        printf '  %-14s recipe here: envs/%s.yml (%s)\n' "" "$RECIPE_STEM" "$RECIPE_REASON"
      fi
    else
      printf '  %-14s not installable on %s: %s\n' "" "${HOST_ARCH:-this host}" "$RECIPE_REASON"
    fi
  done
  exit 0
fi

